from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
PUBLIC = ROOT / "frontend" / "public"
CHAR_DIR = PUBLIC / "characters"
OFFICE_DIR = PUBLIC / "office"

FRAME = 64          # output frame size (px); drawn at 32 and upscaled 2x for crisp pixels
S = 2               # pixel scale
FRAMES = 4          # frames per animation row
ACTIONS = ["idle", "walk", "work", "talk"]
DIRS = ["down", "up", "left", "right"]
FPS = {"idle": 3, "walk": 8, "work": 6, "talk": 5}

LICENSE = {
    "source": "generated by tools/gen_placeholder_art.py (Stock Office)",
    "license": "CC0-1.0",
    "placeholder": True,
}

