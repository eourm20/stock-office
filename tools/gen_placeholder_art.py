"""Generate Stock Office placeholder pixel art, the Tiled office map and the character registry.

Everything here is our own procedurally drawn work, released as CC0-1.0, so placeholders carry
no third-party license risk. Replace any character by editing frontend/public/characters/
registry.json; the map and agent logic do not change.

    uv run --no-project --with pillow python tools/gen_placeholder_art.py
"""

from __future__ import annotations

