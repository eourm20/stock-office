def _px(d: ImageDraw.ImageDraw, x: int, y: int, w: int, h: int, color: tuple[int, ...]) -> None:
    d.rectangle([x, y, x + w - 1, y + h - 1], fill=color)


def draw_person(action: str, direction: str, frame: int, shirt: tuple[int, int, int],
                hair: tuple[int, int, int], accent: tuple[int, int, int]) -> Image.Image:
    """Draw one 32x32 chibi office worker frame (upscaled later)."""
    img = Image.new("RGBA", (32, 32), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    bob = 1 if (action in ("idle", "talk") and frame % 2 == 1) else 0
    seated = action == "work"
    top = 4 + bob + (3 if seated else 0)

    # shadow
    d.ellipse([9, 27, 22, 30], fill=(0, 0, 0, 70))

    # legs
    if seated:
        _px(d, 11, top + 17, 10, 3, PANTS)          # thighs forward
        _px(d, 11, top + 20, 3, 3, PANTS)
        _px(d, 18, top + 20, 3, 3, PANTS)
        _px(d, 10, top + 22, 4, 1, SHOE)
        _px(d, 18, top + 22, 4, 1, SHOE)
    else:
        swing = [0, 2, 0, -2][frame] if action == "walk" else 0
        _px(d, 12, top + 17, 3, 6 - max(0, swing), PANTS)
        _px(d, 17, top + 17, 3, 6 - max(0, -swing), PANTS)
        _px(d, 11, top + 23 - max(0, swing), 4, 1, SHOE)
        _px(d, 17, top + 23 - max(0, -swing), 4, 1, SHOE)

    # body
    _px(d, 10, top + 9, 12, 9, shirt)
    _px(d, 10, top + 9, 12, 1, tuple(max(0, c - 40) for c in shirt))
    if direction == "down":
        _px(d, 15, top + 10, 2, 5, accent)          # tie / lanyard
    # arms
    arm = tuple(max(0, c - 25) for c in shirt)
    if action == "work":
        tap = frame % 2
        _px(d, 8, top + 11, 3, 5, arm)
        _px(d, 21, top + 11, 3, 5, arm)
        _px(d, 9, top + 15 + tap, 3, 2, SKIN)
        _px(d, 20, top + 16 - tap, 3, 2, SKIN)
    elif action == "talk" and frame in (1, 2):
        _px(d, 8, top + 11, 3, 6, arm)
        _px(d, 21, top + 6, 3, 6, arm)              # raised hand
        _px(d, 21, top + 4, 3, 2, SKIN)
    else:
        swing = [0, 1, 0, -1][frame] if action == "walk" else 0
        _px(d, 8, top + 10 + swing, 3, 7, arm)
        _px(d, 21, top + 10 - swing, 3, 7, arm)
        _px(d, 8, top + 17 + swing, 3, 2, SKIN)
        _px(d, 21, top + 17 - swing, 3, 2, SKIN)

    # head
    _px(d, 10, top, 12, 10, SKIN)
    if direction == "up":
        _px(d, 10, top, 12, 8, hair)
    else:
        _px(d, 10, top, 12, 3, hair)
        if direction == "left":
            _px(d, 18, top, 4, 7, hair)
            _px(d, 11, top + 4, 2, 2, OUTLINE)
        elif direction == "right":
            _px(d, 10, top, 4, 7, hair)
            _px(d, 19, top + 4, 2, 2, OUTLINE)
        else:
            _px(d, 10, top, 2, 6, hair)
            _px(d, 20, top, 2, 6, hair)
            _px(d, 13, top + 4, 2, 2, OUTLINE)
            _px(d, 17, top + 4, 2, 2, OUTLINE)
            mouth_open = action == "talk" and frame % 2 == 1
            _px(d, 15, top + 7, 2, 2 if mouth_open else 1, (150, 60, 60))
    return img


def build_sheet(cid: str, shirt: tuple[int, int, int], hair: tuple[int, int, int],
                accent: tuple[int, int, int]) -> dict[str, object]:
    rows = [(a, d) for a in ACTIONS for d in DIRS]
    sheet = Image.new("RGBA", (FRAMES * FRAME, len(rows) * FRAME), (0, 0, 0, 0))
    animations: dict[str, dict[str, dict[str, int]]] = {}
    for r, (action, direction) in enumerate(rows):
        for f in range(FRAMES):
            frame = draw_person(action, direction, f, shirt, hair, accent)
            sheet.paste(frame.resize((FRAME, FRAME), Image.NEAREST), (f * FRAME, r * FRAME))
        animations.setdefault(action, {})[direction] = {"row": r, "frames": FRAMES,
                                                         "fps": FPS[action]}
    sheet.save(CHAR_DIR / f"{cid}.png")
    meta = {"frame_width": FRAME, "frame_height": FRAME, "animations": animations}
    (CHAR_DIR / f"{cid}.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    return meta


# ---------------------------------------------------------------- office art
TW, TH = 64, 32          # isometric tile size
MAP_W, MAP_H = 22, 16

ZONES = {
    # name: (x0, y0, x1, y1) inclusive tile bounds, floor color
    "analyst_office": ((1, 1, 9, 6), (86, 110, 150)),
    "research_room": ((12, 1, 20, 6), (120, 96, 140)),
    "trading_desk": ((1, 9, 9, 14), (80, 130, 120)),
    "risk_executive": ((12, 9, 20, 14), (140, 112, 86)),
}
CORRIDOR = (60, 66, 82)


def iso_tile(color: tuple[int, int, int], edge: tuple[int, int, int] | None = None) -> Image.Image:
    img = Image.new("RGBA", (TW, TH), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    poly = [(TW // 2, 0), (TW - 1, TH // 2), (TW // 2, TH - 1), (0, TH // 2)]
    d.polygon(poly, fill=color)
    light = tuple(min(255, c + 14) for c in color)
    d.line([poly[3], poly[0], poly[1]], fill=light)
    d.line([poly[1], poly[2], poly[3]], fill=edge or tuple(max(0, c - 22) for c in color))
    return img


def iso_box(w: int, h: int, height: int, top: tuple[int, int, int]) -> tuple[Image.Image, ImageDraw.ImageDraw, list]:
    """An isometric block whose footprint is w x h tiles; anchor = bottom center of footprint."""
    width = (w + h) * TW // 2
    img_h = (w + h) * TH // 2 + height
    img = Image.new("RGBA", (width, img_h), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    ox = h * TW // 2
    t = [(ox, 0), (ox + w * TW // 2, w * TH // 2), (ox + (w - h) * TW // 2 + h * TW // 2 - h * TW // 2 + 0, 0)]
    top_poly = [(ox, 0), (ox + w * TW // 2, w * TH // 2), (ox + (w - h) * TW // 2, (w + h) * TH // 2),
                (ox - h * TW // 2, h * TH // 2)]
    left = tuple(max(0, c - 45) for c in top)
    right = tuple(max(0, c - 25) for c in top)
    # side faces
    d.polygon([top_poly[3], top_poly[2], (top_poly[2][0], top_poly[2][1] + height),
               (top_poly[3][0], top_poly[3][1] + height)], fill=left)
    d.polygon([top_poly[2], top_poly[1], (top_poly[1][0], top_poly[1][1] + height),
               (top_poly[2][0], top_poly[2][1] + height)], fill=right)
    d.polygon(top_poly, fill=top)
    del t
    return img, d, top_poly


def furniture() -> dict[str, Image.Image]:
    items: dict[str, Image.Image] = {}
    # desk with monitor (1x1)
    img, d, tp = iso_box(1, 1, 14, (170, 132, 92))
    canvas = Image.new("RGBA", (img.width, img.height + 22), (0, 0, 0, 0))
    canvas.paste(img, (0, 22), img)
    d = ImageDraw.Draw(canvas)
    cx = img.width // 2
    d.rectangle([cx - 13, 6, cx + 13, 24], fill=(30, 34, 46))
    d.rectangle([cx - 11, 8, cx + 11, 21], fill=(90, 200, 255))
    d.line([(cx - 8, 17), (cx - 3, 13), (cx + 2, 15), (cx + 8, 10)], fill=(255, 255, 255), width=1)
    d.rectangle([cx - 2, 24, cx + 2, 30], fill=(30, 34, 46))
    items["desk"] = canvas
    # meeting table 2x2
    items["meeting_table"], _, _ = iso_box(2, 2, 12, (150, 110, 80))
    # plant
    p = Image.new("RGBA", (32, 48), (0, 0, 0, 0))
    d = ImageDraw.Draw(p)
    d.rectangle([10, 32, 21, 45], fill=(150, 90, 60))
    for (x, y, r) in [(16, 18, 9), (10, 24, 7), (22, 24, 7), (16, 10, 6)]:
        d.ellipse([x - r, y - r, x + r, y + r], fill=(70, 150, 80))
    items["plant"] = p
    # server rack (data collector)
    img, d, _ = iso_box(1, 1, 52, (60, 66, 90))
    d = ImageDraw.Draw(img)
    for i in range(5):
        y = 24 + i * 9
        d.line([(10, y + 6), (30, y + 16)], fill=(90, 220, 140) if i % 2 else (255, 190, 80), width=2)
    items["server_rack"] = img
    # whiteboard
    w = Image.new("RGBA", (56, 52), (0, 0, 0, 0))
    d = ImageDraw.Draw(w)
    d.polygon([(4, 4), (52, 16), (52, 40), (4, 28)], fill=(240, 244, 250), outline=(80, 90, 110))
    d.line([(10, 14), (24, 20), (32, 16), (46, 26)], fill=(220, 80, 80), width=2)
    d.line([(26, 34), (26, 50)], fill=(80, 90, 110), width=2)
    items["whiteboard"] = w
    return items


def build_office() -> None:
    OFFICE_DIR.mkdir(parents=True, exist_ok=True)
    tile_colors = [CORRIDOR] + [c for _, c in ZONES.values()]
    tileset = Image.new("RGBA", (TW * len(tile_colors), TH), (0, 0, 0, 0))
    for i, color in enumerate(tile_colors):
        tileset.paste(iso_tile(color), (i * TW, 0))
    tileset.save(OFFICE_DIR / "floor_tiles.png")

    for name, img in furniture().items():
        img.save(OFFICE_DIR / f"{name}.png")

    data: list[int] = []
    for y in range(MAP_H):
        for x in range(MAP_W):
            gid = 1  # corridor
            for i, ((x0, y0, x1, y1), _) in enumerate(ZONES.values()):
                if x0 <= x <= x1 and y0 <= y <= y1:
                    gid = i + 2
            data.append(gid)

    # Spots in tile coordinates. Tiled isometric object coordinates are tile * TH.
    # `desk:<agent>` is the seat in front of a desk (the desk itself is one tile further up).
    spots = {
        # analyst office
        "desk:market_analyst": (3, 2), "home:market_analyst": (4, 3),
        "desk:news_analyst": (6, 2), "home:news_analyst": (7, 3),
        "desk:fundamentals_analyst": (3, 5), "desk:sentiment_analyst": (6, 5),
        "door:analyst_office": (9, 4),
        # research room
        "desk:bull_researcher": (14, 2), "home:bull_researcher": (13, 3),
        "desk:bear_researcher": (18, 2), "home:bear_researcher": (19, 3),
        "meet:bull_researcher": (15, 4), "meet:bear_researcher": (18, 5),
        "desk:research_manager": (16, 2),
        "inbox:research_room": (13, 5),
        "door:research_room": (12, 4),
        # trading desk / risk & executive (Sprint 2B)
        "desk:trader": (4, 11), "door:trading_desk": (9, 11),
        "desk:portfolio_manager": (17, 10), "door:risk_executive": (12, 11),
        "corridor:center": (10, 8),
    }
    objects = []
    oid = 1
    for name, (tx, ty) in spots.items():
        objects.append({"id": oid, "name": name, "type": "spot", "point": True,
                        "x": tx * TH, "y": ty * TH, "width": 0, "height": 0,
                        "rotation": 0, "visible": True})
        oid += 1
    props = [
        ("desk", 3, 1), ("desk", 6, 1), ("desk", 3, 4), ("desk", 6, 4),
        ("desk", 14, 1), ("desk", 18, 1), ("desk", 16, 1), ("meeting_table", 16, 4),
        ("whiteboard", 20, 5), ("server_rack", 1, 1), ("plant", 9, 1), ("plant", 12, 6),
        ("desk", 4, 10), ("desk", 17, 9), ("plant", 1, 14), ("plant", 20, 14),
    ]
    furniture_objs = []
    for kind, tx, ty in props:
        furniture_objs.append({"id": oid, "name": kind, "type": "furniture", "point": True,
                               "x": tx * TH, "y": ty * TH, "width": 0, "height": 0,
                               "rotation": 0, "visible": True,
                               "properties": [{"name": "sprite", "type": "string", "value": kind}]})
        oid += 1
    zone_objs = []
    for name, ((x0, y0, x1, y1), _) in ZONES.items():
        zone_objs.append({"id": oid, "name": name, "type": "zone", "x": x0 * TH, "y": y0 * TH,
                          "width": (x1 - x0 + 1) * TH, "height": (y1 - y0 + 1) * TH,
                          "rotation": 0, "visible": True})
        oid += 1

    tmj = {
        "type": "map", "version": "1.10", "tiledversion": "1.11.0", "orientation": "isometric",
        "renderorder": "right-down", "width": MAP_W, "height": MAP_H, "tilewidth": TW,
        "tileheight": TH, "infinite": False, "nextlayerid": 5, "nextobjectid": oid,
        "layers": [
            {"id": 1, "name": "floor", "type": "tilelayer", "width": MAP_W, "height": MAP_H,
             "data": data, "opacity": 1, "visible": True, "x": 0, "y": 0},
            {"id": 2, "name": "zones", "type": "objectgroup", "objects": zone_objs,
             "opacity": 1, "visible": True, "x": 0, "y": 0},
            {"id": 3, "name": "furniture", "type": "objectgroup", "objects": furniture_objs,
             "opacity": 1, "visible": True, "x": 0, "y": 0},
            {"id": 4, "name": "spots", "type": "objectgroup", "objects": objects,
             "opacity": 1, "visible": True, "x": 0, "y": 0},
        ],
        "tilesets": [{
            "firstgid": 1, "name": "floor_tiles", "image": "floor_tiles.png",
            "imagewidth": TW * len(tile_colors), "imageheight": TH, "tilewidth": TW,
            "tileheight": TH, "tilecount": len(tile_colors), "columns": len(tile_colors),
            "margin": 0, "spacing": 0,
        }],
        "properties": [{"name": "license", "type": "string",
                        "value": "CC0-1.0, generated by tools/gen_placeholder_art.py"}],
    }
    (OFFICE_DIR / "office.tmj").write_text(json.dumps(tmj, indent=1), encoding="utf-8")


def build_characters() -> None:
    CHAR_DIR.mkdir(parents=True, exist_ok=True)
    entries = []
    for cid, (name, shirt, hair, accent) in CHARACTERS.items():
        build_sheet(cid, shirt, hair, accent)
        entries.append({
            "id": cid, "name": name,
            "asset": {"id": f"asset-{cid}", "kind": "sprite_sheet", "image": f"{cid}.png",
                      "metadata": f"{cid}.json"},
            "license": LICENSE,
        })
    registry = {
        "version": 1,
        "default_character": "ph-generic",
        "characters": entries,
        "assignments": {
            "market_analyst": "ph-market",
            "news_analyst": "ph-news",
            "bull_researcher": "ph-bull",
            "bear_researcher": "ph-bear",
        },
    }
    (CHAR_DIR / "registry.json").write_text(json.dumps(registry, indent=2), encoding="utf-8")


if __name__ == "__main__":
    build_characters()
    build_office()
    print("generated:", sorted(p.name for p in CHAR_DIR.iterdir()),
          sorted(p.name for p in OFFICE_DIR.iterdir()))
